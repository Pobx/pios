func setupAPIIntegrationEnv(t *testing.T) *integrationEnv {
	t.Helper()
	if testing.Short() {
		t.Skip("skipping API integration test in -short mode")
	}

	dsn := os.Getenv("TEST_DATABASE_URL")
	if dsn == "" {
		dsn = defaultIntegrationDatabaseURL
	}

	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	t.Cleanup(cancel)

	// 1. Create isolated schema in real PostgreSQL so integration tests are 100% hermetic
	adminPool, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("connect postgres for integration test: %v", err)
	}
	t.Cleanup(adminPool.Close)

	schemaName := fmt.Sprintf("otp_api_it_%d", time.Now().UnixNano())
	if _, err := adminPool.Exec(ctx, fmt.Sprintf(`CREATE SCHEMA "%s"`, schemaName)); err != nil {
		t.Fatalf("create isolated schema %s: %v", schemaName, err)
	}
	t.Cleanup(func() {
		cleanupCtx, c := context.WithTimeout(context.Background(), 5*time.Second)
		defer c()
		_, _ = adminPool.Exec(cleanupCtx, fmt.Sprintf(`DROP SCHEMA IF EXISTS "%s" CASCADE`, schemaName))
	})

	// Configure pool scoped to the isolated schema
	poolCfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parse dsn: %v", err)
	}
	poolCfg.ConnConfig.RuntimeParams["search_path"] = schemaName

	appPool, err := pgxpool.NewWithConfig(ctx, poolCfg)
	if err != nil {
		t.Fatalf("new scoped pool: %v", err)
	}
	t.Cleanup(appPool.Close)

	// Create real organizations table matching 000001_baseline.up.sql and seed test data
	ddl := `
		CREATE TABLE organizations (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			org_code VARCHAR(191) NOT NULL,
			org_type_id BIGINT NOT NULL,
			org_short_name VARCHAR(191) NOT NULL DEFAULT '',
			org_name VARCHAR(191) NOT NULL,
			org_address VARCHAR(191) NOT NULL DEFAULT '',
			org_Lane VARCHAR(191),
			org_road VARCHAR(191),
			org_village_no DOUBLE PRECISION NOT NULL DEFAULT 0,
			org_Subdistrict VARCHAR(191) NOT NULL DEFAULT '',
			org_district VARCHAR(191) NOT NULL DEFAULT '',
			org_province VARCHAR(191) NOT NULL DEFAULT '',
			org_zipcode VARCHAR(191) NOT NULL DEFAULT '',
			org_phone VARCHAR(191) NOT NULL DEFAULT '',
			org_Check_phone VARCHAR(191) NOT NULL DEFAULT '',
			org_fax VARCHAR(191),
			org_email VARCHAR(191),
			org_website VARCHAR(191),
			org_lat DOUBLE PRECISION,
			org_long DOUBLE PRECISION,
			org_logo VARCHAR(191) NOT NULL DEFAULT '',
			org_head_name VARCHAR(191) NOT NULL DEFAULT '',
			org_line_id VARCHAR(191),
			foodwaste_Anchor VARCHAR(191),
			created_at TIMESTAMPTZ,
			updated_at TIMESTAMPTZ
		);
		INSERT INTO organizations (id, org_code, org_type_id, org_name) VALUES
			(1, 'HSG1', 1, 'ห้องแซง'),
			(2, 'TNG1', 5, 'เต่างอย'),
			(3, 'KUCSC', 6, 'เกษตรศาสตร์ วิทยาเขตเฉลิมพระเกียรติ จ.สกลนคร');
	`
	if _, err := appPool.Exec(ctx, ddl); err != nil {
		t.Fatalf("seed organizations in isolated schema: %v", err)
	}

	// 2. Spin up real RS256 JWKS server
	rawRSA, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		t.Fatalf("generate rsa key: %v", err)
	}
	privJWK, err := jwk.FromRaw(rawRSA)
	if err != nil {
		t.Fatalf("jwk from raw: %v", err)
	}
	_ = privJWK.Set(jwk.KeyIDKey, "it-rs256-key-1")
	_ = privJWK.Set(jwk.AlgorithmKey, jwa.RS256)
	_ = privJWK.Set(jwk.KeyUsageKey, "sig")

	pubJWK, err := privJWK.PublicKey()
	if err != nil {
		t.Fatalf("public jwk: %v", err)
	}
	pubSet := jwk.NewSet()
	_ = pubSet.AddKey(pubJWK)

	jwksSrv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		w.Header().Set("Content-Type", "application/json")
		_ = json.NewEncoder(w).Encode(pubSet)
	}))
	t.Cleanup(jwksSrv.Close)

	issuer := "http://localhost:8081/realms/otp"
	audience := "otp-api"

	// 3. Wire real adapters: Keycloak JWKS Verifier + Postgres Store + OrganizationService + Echo HTTP Server
	verifier := keycloak.NewVerifier(keycloak.Config{
		Issuer:   issuer,
		Audience: audience,
		JWKSURL:  jwksSrv.URL,
	})

	store := postgres.NewStore(appPool)
	orgService := app.NewOrganizationService(store)
	handler := httpadapter.NewServer(httpadapter.Deps{
		Verifier:           verifier,
		Organizations:      orgService,
		Health:             store,
		CORSAllowedOrigins: []string{"http://localhost"},
	})

	apiSrv := httptest.NewServer(handler)
	t.Cleanup(apiSrv.Close)

	return &integrationEnv{
		apiServer: apiSrv,
		jwksSrv:   jwksSrv,
		privKey:   privJWK,
		issuer:    issuer,
		audience:  audience,
		client:    apiSrv.Client(),
	}
}

type jwtClaimsSpec struct {
	sub      string
	username string
	roles    []string
	orgID    any
	iss      string
	aud      []string
	exp      time.Time
}

func (env *integrationEnv) signRS256Token(t *testing.T, spec jwtClaimsSpec) string {
	t.Helper()
	iss := spec.iss
	if iss == "" {
		iss = env.issuer
	}
	aud := spec.aud
	if len(aud) == 0 {
		aud = []string{env.audience}
	}
	exp := spec.exp
	if exp.IsZero() {
		exp = time.Now().Add(5 * time.Minute)
	}
	sub := spec.sub
	if sub == "" {
		sub = "user-sub-123"
	}

	b := jwt.NewBuilder().
		Issuer(iss).
		Subject(sub).
		Audience(aud).
		IssuedAt(time.Now().Add(-10 * time.Second)).
		Expiration(exp)

	if spec.username != "" {
		b = b.Claim("preferred_username", spec.username)
	}
	if spec.roles != nil {
		b = b.Claim("realm_access", map[string]any{"roles": spec.roles})
	}
	if spec.orgID != nil {
		b = b.Claim("org_id", spec.orgID)
	}

	tok, err := b.Build()
	if err != nil {
		t.Fatalf("build jwt: %v", err)
	}
	signed, err := jwt.Sign(tok, jwt.WithKey(jwa.RS256, env.privKey))
	if err != nil {
		t.Fatalf("sign jwt: %v", err)
	}
	return string(signed)
}

func (env *integrationEnv) doGET(t *testing.T, path string, bearerToken string) (*http.Response, []byte) {
	t.Helper()
	req, err := http.NewRequest(http.MethodGet, env.apiServer.URL+path, nil)
	if err != nil {
		t.Fatalf("new request: %v", err)
	}
	if bearerToken != "" {
		req.Header.Set("Authorization", "Bearer "+bearerToken)
	}
	resp, err := env.client.Do(req)
	if err != nil {
		t.Fatalf("do request %s: %v", path, err)
	}
	defer resp.Body.Close()
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatalf("read body: %v", err)
	}
	return resp, body
}

func assertIntegrationProblem(t *testing.T, resp *http.Response, body []byte, wantStatus int) problem.Problem {
	t.Helper()
	if resp.StatusCode != wantStatus {
		t.Fatalf("status = %d, want %d (body: %s)", resp.StatusCode, wantStatus, string(body))
	}
	if ct := resp.Header.Get("Content-Type"); ct != problem.ContentType {
		t.Fatalf("content-type = %q, want %q", ct, problem.ContentType)
	}
	var p problem.Problem
	if err := json.Unmarshal(body, &p); err != nil {
		t.Fatalf("unmarshal problem: %v", err)
	}
	if p.Status != wantStatus {
		t.Fatalf("problem.Status = %d, want %d", p.Status, wantStatus)
	}
	return p
}

